// CriandoUsuario insero um usuario no banco de dados
func CriarUsuario(w http.ResponseWriter, r *http.Request) {
	corpoRequest, erro := ioutil.ReadAll(r.Body)
	if erro != nil {
		respostas.Erro(w, http.StatusUnprocessableEntity, erro)
		return
	}

	var usuario modelos.Usuario
	if erro = json.Unmarshal(corpoRequest, &usuario); erro != nil {
		respostas.Erro(w, http.StatusBadRequest, erro)
		return
	}

	if erro = usuario.Preparar("cadastro"); erro != nil {
		respostas.Erro(w, http.StatusBadRequest, erro)
		return
	}

	db, erro := banco.Conectar()
	if erro != nil {
		respostas.Erro(w, http.StatusInternalServerError, erro)
		return
	}
	defer db.Close()

	repositorio := repositorios.NovoRepositorioDeUsuarios(db)
	usuario.ID, erro = repositorio.Criar(usuario)
	if erro != nil {
		var erroMySQL *mysql.MySQLError
		if errors.As(erro, &erroMySQL) && erroMySQL.Number == 1062 {
			respostas.Erro(w, http.StatusConflict, errors.New("Nick ou e-mail já cadastrado"))
			return
		}

		respostas.Erro(w, http.StatusInternalServerError, erro)
		return
	}

	usuario.Senha = ""
	respostas.JSON(w, http.StatusCreated, usuario)
}

// BuscarUsuario busca um usuario salvo no banco
func BuscarUsuario(w http.ResponseWriter, r *http.Request) {
	parametros := mux.Vars(r)

	usuarioID, erro := strconv.ParseUint(parametros["usuarioId"], 10, 64)
	if erro != nil {
		respostas.Erro(w, http.StatusBadRequest, erro)
		return
	}

	db, erro := banco.Conectar()
	if erro != nil {
		respostas.Erro(w, http.StatusInternalServerError, erro)
		return
	}
	defer db.Close()

	repositorio := repositorios.NovoRepositorioDeUsuarios(db)
	usuario, erro := repositorio.BuscarPorID(usuarioID)
	if erro != nil {
		respostas.Erro(w, http.StatusInternalServerError, erro)
		return
	}

	// O e-mail só é devolvido ao próprio usuário
	if usuarioIDNoToken, erro := autenticacao.ExtrairUsuarioID(r); erro != nil || usuarioIDNoToken != usuarioID {
		usuario.Email = ""
	}

	respostas.JSON(w, http.StatusOK, usuario)
}

